package usecase_test

import (
	"bytes"
	"testing"

	"github.com/google/uuid"
	"example.com/hris/backend/internal/usecase"
	"github.com/xuri/excelize/v2"
	"gorm.io/driver/sqlite"
	"gorm.io/gorm"
)

func TestDistributorSales_GenerateExcelTemplate(t *testing.T) {
	// In-memory sqlite db for testing
	db, err := gorm.Open(sqlite.Open(":memory:"), &gorm.Config{})
	if err != nil {
		t.Fatalf("Failed to open sqlite: %v", err)
	}

	uc := usecase.NewDistributorSalesUsecase(db)
	excelBytes, err := uc.GenerateExcelTemplate()
	if err != nil {
		t.Fatalf("GenerateExcelTemplate returned error: %v", err)
	}

	if len(excelBytes) == 0 {
		t.Fatalf("Expected non-empty excel bytes")
	}

	// Verify the generated bytes can be parsed by excelize
	r := bytes.NewReader(excelBytes)
	f, err := excelize.OpenReader(r)
	if err != nil {
		t.Fatalf("Failed to open generated excel: %v", err)
	}
	defer f.Close()

	sheets := f.GetSheetList()
	if len(sheets) == 0 {
		t.Fatalf("Expected at least 1 sheet in template")
	}

	rows, err := f.GetRows(sheets[0])
	if err != nil {
		t.Fatalf("Failed to get rows: %v", err)
	}

	if len(rows) < 2 {
		t.Fatalf("Expected header row and sample rows, got %d rows", len(rows))
	}

	// Verify Header Columns
	header := rows[0]
	expectedCols := []string{
		"Tanggal (YYYY-MM-DD)",
		"Nama Toko / Warung",
		"SKU atau Nama Produk",
		"Jumlah (Qty)",
	}

	for i, col := range expectedCols {
		if i >= len(header) || header[i] != col {
			t.Errorf("Column %d expected '%s', got '%s'", i, col, header[i])
		}
	}
}

func TestDistributorSales_ImportEmptyExcel(t *testing.T) {
	db, err := gorm.Open(sqlite.Open(":memory:"), &gorm.Config{})
	if err != nil {
		t.Fatalf("Failed to open sqlite: %v", err)
	}

	uc := usecase.NewDistributorSalesUsecase(db)

	// Create an empty excel file with only headers
	f := excelize.NewFile()
	_ = f.SetCellValue("Sheet1", "A1", "Tanggal")
	buf := new(bytes.Buffer)
	_ = f.Write(buf)

	distID := uuid.New()
	_, err = uc.ImportSellOutExcel(distID, nil, buf)
	if err == nil {
		t.Fatal("Expected error for empty excel with only headers, got nil")
	}
}
